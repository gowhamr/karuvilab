const fs = require('fs');
const path = require('path');

function main() {
  const toolsDir = path.resolve(process.cwd(), 'src/registry/tools');
  const files = fs.readdirSync(toolsDir).filter(f => f.endsWith('.ts'));

  const coreTools = [];

  for (const file of files) {
    const filePath = path.join(toolsDir, file);
    try {
      const content = fs.readFileSync(filePath, 'utf-8');
      
      // Extract the object part
      // Match from '{' to the end of the file, assuming it's the last thing
      const objectMatch = content.match(/= ({[\s\S]+});/);
      if (!objectMatch) {
        console.warn(`Could not find object in ${file}`);
        continue;
      }

      const jsonStr = objectMatch[1];
      // Note: This is NOT strict JSON, it's a JS object literal.
      // Since it's simple and mostly JSON-like, we can try to evaluate it safely-ish or use a dirty approach.
      // A better way is to use a basic parser or just regex for each field.
      
      const getField = (key) => {
        const regex = new RegExp(`"${key}"\\s*:\\s*([^,\\n]+)`);
        const match = jsonStr.match(regex);
        if (!match) return null;
        let val = match[1].trim();
        // Remove quotes if string
        if (val.startsWith('"') && val.endsWith('"')) {
          val = val.substring(1, val.length - 1);
        } else if (val === 'true') {
          val = true;
        } else if (val === 'false') {
          val = false;
        } else if (val === 'null') {
          val = null;
        } else if (!isNaN(val)) {
          val = Number(val);
        } else if (val.startsWith('[') && val.endsWith(']')) {
           try {
             // Simple array of strings
             return val.substring(1, val.length - 1).split(',').map(s => s.trim().replace(/^"(.*)"$/, '$1')).filter(Boolean);
           } catch { return []; }
        }
        return val;
      };

      const tool = {
        id: getField('id'),
        name: getField('name'),
        desc: getField('desc'),
        href: getField('href'),
        category: getField('category'),
        icon: getField('icon') || null,
        color: getField('color') || null,
        featured: getField('featured') === true,
        popular: getField('popular') === true,
        status: getField('status') || 'stable',
        lastAdded: getField('lastAdded') || null,
        keywords: getField('keywords') || [],
        input: getField('input') || null,
        output: getField('output') || null,
        related: getField('related') || [],
        subCategory: getField('subCategory') || null,
        requiresNetwork: getField('requiresNetwork') === true
      };

      if (tool.id) {
        coreTools.push(tool);
      }
    } catch (err) {
      console.error(`Error processing tool ${file}:`, err);
    }
  }

  const outputContent = `// This file is auto-generated by scripts/generate-registries.js. Do not edit directly.
export const CORE_TOOLS = ${JSON.stringify(coreTools, null, 2)};
`;

  const outputPath = path.resolve(process.cwd(), 'src/registry/core-registry.ts');
  fs.writeFileSync(outputPath, outputContent);
  console.log(`✅ Core registry compiled successfully with ${coreTools.length} tools (Pure JS fallback).`);
}

main();
